"""Native clipboard agents: notice local copies and write clips that arrive.

The agent runs in the app's process on a background thread, so the clipboard
keeps syncing with no window open (see ``docs/sync.md``). Each platform has a
cheap change counter to poll, so the text itself is only read when it changed
and sync is on:

- **macOS:** ``NSPasteboard.changeCount`` (AppKit, bundled with the desktop
  app), else ``pbpaste``/``pbcopy``.
- **Windows:** ``GetClipboardSequenceNumber`` and the Win32 clipboard (ctypes).
- **Linux:** ``wl-paste``/``wl-copy`` on Wayland, ``xclip`` or ``xsel`` on X11.

Password managers mark what they copy (``org.nspasteboard.ConcealedType`` on
macOS, ``ExcludeClipboardContentFromMonitorProcessing`` on Windows,
``x-kde-passwordManagerHint`` on Linux); those copies are reported as
*concealed* and never synced automatically. Clips this agent writes carry its
own marker, so they are never reported back as new copies.
"""

from __future__ import annotations

import contextlib
import hashlib
import logging
import os
import shutil
import subprocess
import sys
import threading
import time
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any, Protocol

if TYPE_CHECKING:
    from open_transfer.sync.engine import SyncEngine

log = logging.getLogger("open_transfer.clipboard")

#: Marks clips this agent wrote (a pasteboard type on macOS, a format on Windows).
OUR_TYPE = "io.github.itsonu.open-transfer.synced"
MAC_PRIVATE_TYPES = (
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
)
MAX_READ_BYTES = 1024 * 1024 + 1
POLL_SECONDS = 0.5
COMMAND_TIMEOUT = 3.0


@dataclass(frozen=True)
class Snapshot:
    """What is on the clipboard: its text (``None``: no text), and what we know about it."""

    text: str | None
    concealed: bool = False
    ours: bool = False
    source: str = ""


class Agent(Protocol):
    name: str
    #: True when noticing a change means reading the clipboard (no change counter).
    reads_to_detect: bool

    def change_token(self) -> object: ...

    def read(self) -> Snapshot: ...

    def write(self, text: str, *, sensitive: bool) -> bool: ...


# ===================================================================== macOS


class MacAgent:
    """NSPasteboard through PyObjC (always present in the packaged macOS app)."""

    name = "macos"
    reads_to_detect = False

    def __init__(self) -> None:
        import AppKit  # type: ignore[import-not-found]

        self._appkit = AppKit
        self._pb = AppKit.NSPasteboard.generalPasteboard()
        self._string = AppKit.NSPasteboardTypeString

    def change_token(self) -> object:
        return int(self._pb.changeCount())

    def read(self) -> Snapshot:
        types = {str(t) for t in (self._pb.types() or [])}
        text = self._pb.stringForType_(self._string)
        return Snapshot(
            None if text is None else str(text),
            concealed=bool(types & set(MAC_PRIVATE_TYPES)),
            ours=OUR_TYPE in types,
            source=self._frontmost(),
        )

    def _frontmost(self) -> str:
        with contextlib.suppress(Exception):
            app = self._appkit.NSWorkspace.sharedWorkspace().frontmostApplication()
            return str(app.bundleIdentifier() or app.localizedName() or "")
        return ""

    def write(self, text: str, *, sensitive: bool) -> bool:
        pb = self._pb
        pb.clearContents()
        ok = bool(pb.setString_forType_(text, self._string))
        pb.setString_forType_("1", OUR_TYPE)
        if sensitive:  # clipboard managers skip it, like a password manager's copy
            pb.setString_forType_("", "org.nspasteboard.ConcealedType")
        return ok


class CommandAgent:
    """Clipboard tools on the PATH: ``pbpaste``, ``wl-paste``, ``xclip``, ``xsel``.

    No change counter, so the token is a digest of the text (read at most every
    poll, and only while sync is on). No markers either; the sync engine's
    echo check covers our writes.
    """

    reads_to_detect = True

    def __init__(
        self,
        name: str,
        paste: list[str],
        copy: list[str],
        types: list[str] | None = None,
        private_type: str = "",
    ) -> None:
        self.name = name
        self._paste, self._copy, self._types = paste, copy, types
        self._private_type = private_type

    def _run(self, cmd: list[str], data: bytes | None = None) -> bytes | None:
        try:
            done = subprocess.run(  # noqa: S603 - fixed commands, no shell
                cmd,
                input=data,
                capture_output=True,
                timeout=COMMAND_TIMEOUT,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            return None
        return done.stdout if done.returncode == 0 else None

    def change_token(self) -> object:
        out = self._run(self._paste)
        return None if out is None else hashlib.sha256(out[:MAX_READ_BYTES]).hexdigest()

    def read(self) -> Snapshot:
        out = self._run(self._paste)
        if out is None:
            return Snapshot(None)
        concealed = False
        if self._types and self._private_type:
            listed = self._run(self._types) or b""
            concealed = self._private_type.encode() in listed
        return Snapshot(out[:MAX_READ_BYTES].decode("utf-8", "replace"), concealed=concealed)

    def write(self, text: str, *, sensitive: bool) -> bool:
        return self._run(self._copy, text.encode()) is not None


# =================================================================== Windows


class WindowsAgent:
    """The Win32 clipboard through ctypes (no extra packages)."""

    name = "windows"
    reads_to_detect = False
    CF_UNICODETEXT = 13
    GMEM_MOVEABLE = 0x0002

    def __init__(self) -> None:
        import ctypes
        from ctypes import wintypes

        self._ct = ctypes
        user32 = ctypes.WinDLL("user32", use_last_error=True)  # type: ignore[attr-defined]
        kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)  # type: ignore[attr-defined]
        handle = ctypes.c_void_p
        user32_api: list[tuple[str, list[Any], Any]] = [
            ("GetClipboardSequenceNumber", [], wintypes.DWORD),
            ("OpenClipboard", [wintypes.HWND], wintypes.BOOL),
            ("CloseClipboard", [], wintypes.BOOL),
            ("EmptyClipboard", [], wintypes.BOOL),
            ("IsClipboardFormatAvailable", [wintypes.UINT], wintypes.BOOL),
            ("GetClipboardData", [wintypes.UINT], handle),
            ("SetClipboardData", [wintypes.UINT, handle], handle),
            ("RegisterClipboardFormatW", [wintypes.LPCWSTR], wintypes.UINT),
            ("GetForegroundWindow", [], wintypes.HWND),
            (
                "GetWindowThreadProcessId",
                [wintypes.HWND, ctypes.POINTER(wintypes.DWORD)],
                wintypes.DWORD,
            ),
            (
                "CreateWindowExW",
                [wintypes.DWORD, wintypes.LPCWSTR, wintypes.LPCWSTR, wintypes.DWORD]
                + [ctypes.c_int] * 4
                + [wintypes.HWND, wintypes.HMENU, wintypes.HINSTANCE, wintypes.LPVOID],
                wintypes.HWND,
            ),
            ("DestroyWindow", [wintypes.HWND], wintypes.BOOL),
        ]
        kernel32_api: list[tuple[str, list[Any], Any]] = [
            ("GlobalAlloc", [wintypes.UINT, ctypes.c_size_t], handle),
            ("GlobalLock", [handle], ctypes.c_void_p),
            ("GlobalUnlock", [handle], wintypes.BOOL),
            ("GlobalSize", [handle], ctypes.c_size_t),
            ("GlobalFree", [handle], handle),
            ("OpenProcess", [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD], handle),
            ("CloseHandle", [handle], wintypes.BOOL),
            (
                "QueryFullProcessImageNameW",
                [handle, wintypes.DWORD, wintypes.LPWSTR, ctypes.POINTER(wintypes.DWORD)],
                wintypes.BOOL,
            ),
        ]
        for dll, api in ((user32, user32_api), (kernel32, kernel32_api)):
            for name, args, res in api:
                fn = getattr(dll, name)
                fn.argtypes, fn.restype = args, res
        self._user32, self._kernel32 = user32, kernel32
        register = user32.RegisterClipboardFormatW
        self._ours = register(OUR_TYPE)
        # Set by password managers (and Windows itself for some copies).
        self._exclude = register("ExcludeClipboardContentFromMonitorProcessing")
        self._no_history = register("CanIncludeInClipboardHistory")
        self._no_cloud = register("CanUploadToCloudClipboard")

    def change_token(self) -> object:
        return int(self._user32.GetClipboardSequenceNumber())

    @contextlib.contextmanager
    def _opened(self, *, owner: bool = False) -> Any:
        # Writing needs a window to own the clipboard ("If an application calls
        # OpenClipboard with hwnd set to NULL, EmptyClipboard sets the clipboard
        # owner to NULL; this causes SetClipboardData to fail"): a hidden one.
        hwnd = (
            self._user32.CreateWindowExW(0, "STATIC", None, 0, 0, 0, 0, 0, None, None, None, None)
            if owner
            else None
        )
        try:
            # Another app may hold the clipboard for a moment: retry briefly.
            for _ in range(20):
                if self._user32.OpenClipboard(hwnd):
                    break
                time.sleep(0.02)
            else:
                raise OSError("the clipboard is busy")
            try:
                yield
            finally:
                self._user32.CloseClipboard()
        finally:
            if hwnd:
                self._user32.DestroyWindow(hwnd)

    def _dword(self, fmt: int) -> int | None:
        """The DWORD stored in a clipboard format (``None``: not there)."""
        if not self._user32.IsClipboardFormatAvailable(fmt):
            return None
        data = self._user32.GetClipboardData(fmt)
        if not data or self._kernel32.GlobalSize(data) < 4:
            return 1
        ptr = self._kernel32.GlobalLock(data)
        try:
            return int(self._ct.c_uint32.from_address(ptr).value) if ptr else 1
        finally:
            self._kernel32.GlobalUnlock(data)

    def read(self) -> Snapshot:
        with self._opened():
            ours = bool(self._user32.IsClipboardFormatAvailable(self._ours))
            concealed = bool(self._user32.IsClipboardFormatAvailable(self._exclude)) or (
                self._dword(self._no_history) == 0
            )
            text: str | None = None
            if self._user32.IsClipboardFormatAvailable(self.CF_UNICODETEXT):
                data = self._user32.GetClipboardData(self.CF_UNICODETEXT)
                if data:
                    ptr = self._kernel32.GlobalLock(data)
                    if ptr:
                        try:
                            limit = self._kernel32.GlobalSize(data) // 2
                            text = self._ct.wstring_at(ptr, limit).split("\0", 1)[0]
                        finally:
                            self._kernel32.GlobalUnlock(data)
        return Snapshot(text, concealed=concealed, ours=ours, source=self._source())

    def _source(self) -> str:
        """The program in front (``notepad.exe``), for the blocked-apps list."""
        ct = self._ct
        from ctypes import wintypes

        with contextlib.suppress(Exception):
            pid = wintypes.DWORD()
            self._user32.GetWindowThreadProcessId(self._user32.GetForegroundWindow(), ct.byref(pid))
            process = self._kernel32.OpenProcess(
                0x1000, False, pid.value
            )  # QUERY_LIMITED_INFORMATION
            if process:
                try:
                    size = wintypes.DWORD(1024)
                    buf = ct.create_unicode_buffer(size.value)
                    if self._kernel32.QueryFullProcessImageNameW(process, 0, buf, ct.byref(size)):
                        return os.path.basename(str(buf.value))
                finally:
                    self._kernel32.CloseHandle(process)
        return ""

    def _put(self, fmt: int, payload: bytes) -> bool:
        memory = self._kernel32.GlobalAlloc(self.GMEM_MOVEABLE, len(payload))
        if not memory:
            return False
        ptr = self._kernel32.GlobalLock(memory)
        if not ptr:
            self._kernel32.GlobalFree(memory)
            return False
        self._ct.memmove(ptr, payload, len(payload))
        self._kernel32.GlobalUnlock(memory)
        if not self._user32.SetClipboardData(fmt, memory):
            self._kernel32.GlobalFree(memory)  # still ours: free it
            return False
        return True  # the clipboard owns the memory now

    def write(self, text: str, *, sensitive: bool) -> bool:
        with self._opened(owner=True):
            self._user32.EmptyClipboard()
            ok = self._put(self.CF_UNICODETEXT, (text + "\0").encode("utf-16-le"))
            self._put(self._ours, b"\1\0\0\0")
            if sensitive:  # keep it out of Win+V history and the cloud clipboard
                self._put(self._no_history, b"\0\0\0\0")
                self._put(self._no_cloud, b"\0\0\0\0")
        return ok


# ================================================================== choosing


def detect(platform: str | None = None) -> Agent | None:
    """The best clipboard agent for this machine, or ``None``."""
    plat = platform or sys.platform
    try:
        if plat == "darwin":
            try:
                return MacAgent()
            except Exception:  # no PyObjC (a pip install without the desktop extra)
                if shutil.which("pbpaste") and shutil.which("pbcopy"):
                    return CommandAgent("macos-pbcopy", ["pbpaste"], ["pbcopy"])
                return None
        if plat == "win32":
            return WindowsAgent()
        if plat.startswith("linux"):
            if (
                os.environ.get("WAYLAND_DISPLAY")
                and shutil.which("wl-paste")
                and shutil.which("wl-copy")
            ):
                return CommandAgent(
                    "wayland",
                    ["wl-paste", "--no-newline", "--type", "text"],
                    ["wl-copy", "--type", "text/plain;charset=utf-8"],
                    types=["wl-paste", "--list-types"],
                    private_type="x-kde-passwordManagerHint",
                )
            if os.environ.get("DISPLAY"):
                if shutil.which("xclip"):
                    return CommandAgent(
                        "x11-xclip",
                        ["xclip", "-selection", "clipboard", "-out"],
                        ["xclip", "-selection", "clipboard", "-in"],
                        types=["xclip", "-selection", "clipboard", "-out", "-target", "TARGETS"],
                        private_type="x-kde-passwordManagerHint",
                    )
                if shutil.which("xsel"):
                    return CommandAgent(
                        "x11-xsel",
                        ["xsel", "--clipboard", "--output"],
                        ["xsel", "--clipboard", "--input"],
                    )
    except Exception:
        log.warning("No clipboard access on this computer", exc_info=True)
    return None


# =================================================================== watcher


class Watcher:
    """Polls the agent and feeds the sync engine; writes the clips it hands back."""

    def __init__(self, agent: Agent, engine: SyncEngine, *, interval: float = POLL_SECONDS) -> None:
        self.agent = agent
        self.engine = engine
        self.interval = interval
        self._lock = threading.Lock()
        self._token: object = None
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self.failures = 0

    def start(self) -> Watcher:
        with contextlib.suppress(Exception):
            self._token = self.agent.change_token()  # what's there now isn't a new copy
        self.engine.set_writer(self.write)
        self.engine.before_apply = self.poll
        self._thread = threading.Thread(target=self._run, name="ot-clipboard", daemon=True)
        self._thread.start()
        log.info("Watching the clipboard (%s)", self.agent.name)
        return self

    def stop(self) -> None:
        self._stop.set()
        self.engine.set_writer(None)
        self.engine.before_apply = None

    def poll(self) -> None:
        """Report a local copy, if there's a new one (also called just before a clip is applied)."""
        if self.agent.reads_to_detect and not self.engine.active():
            return
        with self._lock:
            token = self.agent.change_token()
            if token is None or token == self._token:
                return
            self._token = token
            if not self.engine.active():
                return  # sync is off: don't even look at what was copied
            snapshot = self.agent.read()
        if snapshot.ours or not snapshot.text:
            return
        self.engine.copy(snapshot.text, source=snapshot.source, concealed=snapshot.concealed)

    def write(self, text: str, info: dict[str, Any]) -> bool:
        with self._lock:
            ok = self.agent.write(text, sensitive=bool(info.get("sensitive")))
            with contextlib.suppress(Exception):
                self._token = self.agent.change_token()  # our own write isn't a copy
        return ok

    def _run(self) -> None:
        while not self._stop.wait(self.interval * (1 + min(self.failures, 20))):
            try:
                self.poll()
                self.failures = 0
            except Exception:
                # Keep going (the clipboard can be busy, or the session locked); back off.
                self.failures += 1
                if self.failures in (1, 10, 100):
                    log.warning("Couldn’t read the clipboard", exc_info=True)
